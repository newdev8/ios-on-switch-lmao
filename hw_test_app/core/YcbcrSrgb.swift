    /// The read's linear step of sRGB step `s`: the knots joined by lines, rounded to nearest even.
    static func decode(_ s: Int) -> UInt32 {
        let i = min(s >> 4, 511), f = UInt32(s - 16 * i)
        let n = 16 * knots[i] + (knots[i + 1] - knots[i]) * f
        return (n + 7 + ((n >> 4) & 1)) >> 4
    }

    /// E[q], q = 0 ... 8192
    public static let encode: [UInt16] = {
        let decoded = (0...8192).map(decode)
        var table = [UInt16](repeating: 0, count: 8193)
        var first = 0
        for q in UInt32(1)...8192 {
            while decoded[first] < q { first += 1 }
            var end = first
            while end <= 8192 && decoded[end] == q { end += 1 }
            var (lo, hi) = (first, end - 1)
            if end == first {
                let below = q - decoded[first - 1], above = decoded[first] - q
                lo = below <= above ? first - 1 : first
                hi = above <= below ? first : first - 1
            }
            table[Int(q)] = UInt16((lo + hi + 1) / 2)
        }
        return table
    }()
