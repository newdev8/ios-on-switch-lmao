"""Write SwitchGM20BCaps.h and gm20b_caps.json from kits/SwitchGM20B/caps.

The header holds C tables for the kernel and user space, C and C++; the JSON every row, for tools. Any row caps.py
rejects fails the generator.
"""

import argparse
import glob
import json
import os
import re

import caps
import formats

GRADE = {g: f'SWITCH_GM20B_GRADE_{g.upper()}' for g in caps.GRADES}

PREAMBLE = """// Generated by kits/SwitchGM20B/caps/gen_caps.py from caps/*.tsv: do not edit.
#ifndef SWITCH_GM20B_CAPS_H
#define SWITCH_GM20B_CAPS_H

#include <stdint.h>

#ifdef __cplusplus
#define SWITCH_GM20B_CAPS_TABLE constexpr
#else
#define SWITCH_GM20B_CAPS_TABLE static const
#endif

enum switch_gm20b_grade {
    SWITCH_GM20B_GRADE_SOURCE,
    SWITCH_GM20B_GRADE_HOST,
    SWITCH_GM20B_GRADE_CHIP,
};
"""

FORMAT_STRUCT = """
struct switch_gm20b_format {
    uint16_t mtl;
    uint16_t flags;
    uint32_t tic0;
    uint8_t ct, zt, kind, msaa;
    uint8_t bytes, block_w, block_h, grade;
};
"""


def ident(text: str) -> str:
    return re.sub(r'\W', '_', text).upper()


def format_rows(table: caps.Caps, args: argparse.Namespace) -> list[dict]:
    src = formats.Sources(
        nil=caps.read_nil(args.nil_csv),
        format_class=formats.nil_format_class(os.path.dirname(args.nil_gen)),
        headers=caps.Headers(args.classes, args.tegra),
        blocks=formats.block_info(args.u_format),
        render_samples=next(r.cols['value'] for r in table.limits if r.cols['name'] == 'render_sample_counts'),
    )
    return [formats.derive(r, src) for r in table.formats]


def header_text(table: caps.Caps, rows: list[dict]) -> str:
    out = [PREAMBLE]
    for i, name in enumerate(formats.FLAGS):
        out.append(f'#define SWITCH_GM20B_FORMAT_{name.upper()} (1u << {i})')
    out.append(FORMAT_STRUCT)
    out.append('SWITCH_GM20B_CAPS_TABLE struct switch_gm20b_format switch_gm20b_formats[] = {')
    for r in rows:
        flags = ' | '.join(f'SWITCH_GM20B_FORMAT_{f.upper()}' for f in r['flags']) or '0'
        out.append(
            f'    {{{r["mtl"]}, {flags}, 0x{r["tic0"]:08x}, 0x{r["ct"]:02x}, 0x{r["zt"]:02x}, 0x{r["kind"]:02x}, '
            f'{r["msaa"]}, {r["bytes"]}, {r["block_w"]}, {r["block_h"]}, {GRADE[r["grade"]]}}},  // {r["name"]}'
        )
    out += ['};', f'#define SWITCH_GM20B_FORMAT_COUNT {len(rows)}u', '']
    for r in table.limits:
        name, value = ident(r.cols['name']), r.cols['value']
        if ',' in value:
            value = str(formats.sample_mask(value))
        out.append(f'#define SWITCH_GM20B_LIMIT_{name} {value}u')
        out.append(f'#define SWITCH_GM20B_LIMIT_{name}_GRADE {GRADE[r.cols["grade"]]}')
    out += ['', 'enum switch_gm20b_feature {']
    for r in table.features:
        out.append(f'    SWITCH_GM20B_FEATURE_{ident(r.cols["id"])},')
    out += ['    SWITCH_GM20B_FEATURE_COUNT,', '};', '']
    out += ['struct switch_gm20b_feature_row {', '    uint8_t present, grade;', '};', '']
    out.append('SWITCH_GM20B_CAPS_TABLE struct switch_gm20b_feature_row switch_gm20b_features[] = {')
    for r in table.features:
        present = 1 if r.cols['present'] == 'yes' else 0
        out.append(f'    {{{present}, {GRADE[r.cols["grade"]]}}},  // {r.cols["id"]} {r.cols["capability"]}')
    out += ['};', '', '#endif', '']
    return '\n'.join(out)


def json_text(table: caps.Caps, rows: list[dict]) -> str:
    doc = {
        'formats': [
            dict(r, **{k: v for k, v in t.cols.items() if k not in r}) for r, t in zip(rows, table.formats, strict=True)
        ],
        'limits': [t.cols for t in table.limits],
        'features': [t.cols for t in table.features],
        'methods': [t.cols for t in table.methods],
    }
    return json.dumps(doc, indent=1, sort_keys=True) + '\n'


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument('--tables', required=True, help='the directory of the .tsv files')
    parser.add_argument('--root', help='the repository root: also check that cited files and lines exist')
    parser.add_argument('--classes', required=True, help="Mesa's nvidia/classes directory")
    parser.add_argument('--tegra', required=True, help='kits/SwitchGM20B/SwitchGM20BTegra.h')
    parser.add_argument('--nil-csv', required=True)
    parser.add_argument('--nil-gen', required=True, help="Mesa's nil_format_table_gen.py")
    parser.add_argument('--u-format', required=True, help="Mesa's u_format.yaml")
    parser.add_argument('--hwtest-source', action='append', default=[])
    parser.add_argument('--out-h')
    parser.add_argument('--out-json')
    return parser.parse_args(argv)


def runfiles_args(root: str | None = None) -> argparse.Namespace:
    """Name the inputs where a py_binary's or py_test's runfiles put them (the working directory)."""
    m = 'third_party/mesa/src/'
    swift = sorted(glob.glob('hw_test_app/**/*.swift', recursive=True))
    return parse_args(
        [
            '--tables',
            'kits/SwitchGM20B/caps',
            '--classes',
            m + 'nouveau/headers/nvidia/classes',
            '--tegra',
            'kits/SwitchGM20B/SwitchGM20BTegra.h',
            '--nil-csv',
            m + 'nouveau/nil/nil_formats.csv',
            '--nil-gen',
            m + 'nouveau/nil/nil_format_table_gen.py',
            '--u-format',
            m + 'util/format/u_format.yaml',
        ]
        + [a for f in swift for a in ('--hwtest-source', f)]
        + (['--root', root] if root else [])
    )


def build(args: argparse.Namespace) -> tuple[caps.Caps, list[dict]]:
    headers = caps.Headers(args.classes, args.tegra)
    table = caps.load(args.tables, args.root, headers, caps.hw_test_ids(args.hwtest_source))
    rows = format_rows(table, args)
    return table, rows


def main() -> None:
    args = parse_args()
    try:
        table, rows = build(args)
    except caps.CapsError as e:
        caps.fail(e)
    if args.out_h:
        with open(args.out_h, 'w', encoding='utf-8') as f:
            f.write(header_text(table, rows))
    if args.out_json:
        with open(args.out_json, 'w', encoding='utf-8') as f:
            f.write(json_text(table, rows))


if __name__ == '__main__':
    main()
