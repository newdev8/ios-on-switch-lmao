#!/usr/bin/env python3
"""Write SwitchGM20BVkFormats.h: per VkFormat, NIL's texture header word 0 and whether it takes storage and is integer.

usage: gen_vk_formats.py --vk-format <vk_format.c> --vulkan-core <vulkan_core.h> --classes <clb197.h> --tegra <header>
                         --nil-csv <nil_formats.csv> --nil-gen <nil_format_table_gen.py> --u-format <u_format.yaml>
                         (--out <header> | --check <header>)

The VkFormat to pipe format map is Mesa's vk_format_to_pipe_format (vk_format.c), which NVK's views take. A format
NIL has no row for is left out. --check fails when the header differs from what the inputs make.
"""

import argparse
import os
import re
import sys

import caps
import formats
import yaml

HEADER = """// Generated by kits/SwitchGM20B/caps/gen_vk_formats.py from vk_format.c, nil_formats.csv and u_format.yaml.
#pragma once
#include <stdint.h>

#define SWITCH_GM20B_VK_FORMAT_STORAGE 1u
#define SWITCH_GM20B_VK_FORMAT_INTEGER 2u

struct switch_gm20b_vk_format {{
    uint32_t vk, tic0, flags;
}};

#define SWITCH_GM20B_VK_FORMATS {count}u

// By VkFormat
static const struct switch_gm20b_vk_format switch_gm20b_vk_formats[SWITCH_GM20B_VK_FORMATS] = {{
{rows}
}};
"""


def vk_to_pipe(path: str) -> dict[str, str]:
    with open(path, encoding='utf-8') as f:
        text = f.read()
    pairs = re.findall(r'\[VK_FORMAT_(\w+)\]\s*=\s*PIPE_FORMAT_(\w+)', text)
    pairs += re.findall(r'case VK_FORMAT_(\w+):\s*return PIPE_FORMAT_(\w+);', text)
    return dict(pairs)


def vk_values(path: str) -> dict[str, int]:
    with open(path, encoding='utf-8') as f:
        text = f.read()
    return {name: int(v) for name, v in re.findall(r'^\s+VK_FORMAT_(\w+) = (\d+),', text, re.MULTILINE)}


def pure_integer(entry: dict) -> bool:
    channels = entry.get('channels') or (entry.get('little_endian') or {}).get('channels') or []
    swizzles = entry.get('swizzles') or (entry.get('little_endian') or {}).get('swizzles') or []
    if entry.get('colorspace') == 'ZS':
        return not swizzles or swizzles[0] == '_'
    first = next((c for c in channels if not c.startswith('X')), None)
    return first is not None and first[0] in 'US' and first[1] == 'P'


def rows(args: argparse.Namespace) -> list[tuple[int, int, int]]:
    nil = caps.read_nil(args.nil_csv)
    format_class = formats.nil_format_class(os.path.dirname(args.nil_gen))
    classes = args.classes if os.path.isdir(args.classes) else os.path.dirname(args.classes)
    headers = caps.Headers(classes, args.tegra)
    with open(args.u_format, encoding='utf-8') as f:
        described = {e['name']: e for e in yaml.safe_load(f)}
    values = vk_values(args.vulkan_core)
    out = []
    for vk, pipe in vk_to_pipe(args.vk_format).items():
        if pipe not in nil or vk not in values or pipe not in described:
            continue
        fmt = format_class(nil[pipe])
        flags = (1 if 'S' in fmt._support else 0) | (2 if pure_integer(described[pipe]) else 0)
        out.append((values[vk], formats.tic_word0(fmt, headers), flags))
    return sorted(set(out))


def header(made: list[tuple[int, int, int]]) -> str:
    lines = '\n'.join(f'    {{{vk}, 0x{tic0:08x}, {flags}}},' for vk, tic0, flags in made)
    return HEADER.format(count=len(made), rows=lines)


def main() -> None:
    p = argparse.ArgumentParser()
    for name in ('vk-format', 'vulkan-core', 'classes', 'tegra', 'nil-csv', 'nil-gen', 'u-format'):
        p.add_argument('--' + name, required=True)
    p.add_argument('--out')
    p.add_argument('--check')
    args = p.parse_args()
    try:
        text = header(rows(args))
    except caps.CapsError as e:
        sys.exit(f'gen_vk_formats: {e}')
    if args.check:
        with open(args.check, encoding='utf-8') as f:
            if f.read() != text:
                sys.exit(f'gen_vk_formats: {args.check} is not what its inputs make: run gen_vk_formats.py --out')
        return
    with open(args.out, 'w', encoding='utf-8') as f:
        f.write(text)


if __name__ == '__main__':
    main()
